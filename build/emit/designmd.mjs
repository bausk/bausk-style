// DESIGN.md in the google-labs-code/design.md format (version "alpha"), so any agent or
// tool that reads that format (Stitch, Impeccable, plain coding agents) gets the look.
// Lint: npx @google/design.md lint dist/design/<brand>.<look>.DESIGN.md

const px = (v) => (String(v) === '0' ? '0px' : String(v));

export function designMd(look, brand, meta, { projectRules = '' } = {}) {
  const t = look.color.light;
  const v = look.values;
  const q = (s) => JSON.stringify(String(s));
  const typo = (role, size, weight, lead, track = '0em') => [
    `    fontFamily: ${q(look.fonts[role].family)}`,
    `    fontSize: ${size}`,
    `    fontWeight: ${weight}`,
    `    lineHeight: ${lead}`,
    `    letterSpacing: ${track === '0' ? '0em' : track}`,
  ].join('\n');
  const colors = {
    primary: t.accent, 'on-primary': t['on-accent'], 'primary-strong': t['accent-strong'], 'primary-subtle': t['accent-subtle'],
    secondary: t['fg-muted'], tertiary: t['viz-3'], neutral: t.bg,
    background: t.bg, surface: t['bg-subtle'], 'inverse-surface': t['bg-inverse'], 'on-inverse': t['fg-inverse'],
    'on-surface': t.fg, 'on-surface-muted': t['fg-muted'], 'on-surface-subtle': t['fg-subtle'],
    outline: t.line, 'outline-strong': t['line-strong'],
    positive: t.positive, negative: t.negative, caution: t.caution,
    ...Object.fromEntries([1, 2, 3, 4, 5, 6].map((i) => [`viz-${i}`, t[`viz-${i}`]])),
    'viz-up': t['viz-up'], 'viz-down': t['viz-down'],
  };
  const fm = `---
version: alpha
name: ${q(`${brand.name.en} · ${look.name.en}`)}
description: ${q(look.reference)}
colors:
${Object.entries(colors).map(([k, c]) => `  ${k}: "${c}"`).join('\n')}
typography:
  display:
${typo('display', v['size-4xl'], v['weight-display'], v['leading-tight'], v['tracking-display'])}
  h1:
${typo('display', v['size-3xl'], v['weight-display'], v['leading-tight'], v['tracking-display'])}
  h2:
${typo('display', v['size-xl'], v['weight-display'], v['leading-tight'], v['tracking-display'])}
  body-md:
${typo('text', v['size-text'], v['weight-regular'], v['leading-text'])}
  ui-md:
${typo('ui', v['size-md'], v['weight-regular'], v['leading-ui'])}
  label:
${typo('ui', v['size-xs'], v['label-weight'], v['leading-ui'], v['tracking-label'])}
  mono:
${typo('mono', v['size-sm'], v['weight-regular'], v['leading-ui'])}
rounded:
  none: 0px
  surface: ${px(v.radius)}
  control: ${px(v['radius-control'])}
spacing:
  xs: ${v['space-2']}
  sm: ${v['space-3']}
  md: ${v['space-5']}
  lg: ${v['space-6']}
  xl: ${v['space-7']}
  xxl: ${v['space-8']}
components:
  button-primary:
    backgroundColor: "{colors.primary}"
    textColor: "{colors.on-primary}"
    typography: "{typography.ui-md}"
    rounded: "{rounded.control}"
    height: ${v['control-h']}
  button-primary-hover:
    backgroundColor: "{colors.primary-strong}"
  button-secondary:
    backgroundColor: "{colors.background}"
    textColor: "{colors.on-surface}"
    rounded: "{rounded.control}"
  link:
    textColor: "{colors.primary}"
  selection:
    backgroundColor: "{colors.primary-subtle}"
  page:
    backgroundColor: "{colors.background}"
    textColor: "{colors.on-surface}"
    typography: "{typography.body-md}"
  well:
    backgroundColor: "{colors.surface}"
    textColor: "{colors.on-surface}"
    rounded: "{rounded.surface}"
  label:
    textColor: "{colors.on-surface-subtle}"
    typography: "{typography.label}"
  standfirst:
    textColor: "{colors.on-surface-muted}"
  inverse-band:
    backgroundColor: "{colors.inverse-surface}"
    textColor: "{colors.on-inverse}"
  divider:
    backgroundColor: "{colors.outline}"
  control-border:
    backgroundColor: "{colors.outline-strong}"
  status-positive:
    textColor: "{colors.positive}"
  status-negative:
    textColor: "{colors.negative}"
  status-caution:
    textColor: "{colors.caution}"
  chart:
    backgroundColor: "{colors.background}"
    textColor: "{colors.on-surface-subtle}"
  chart-series-1:
    backgroundColor: "{colors.viz-1}"
  chart-series-2:
    backgroundColor: "{colors.viz-2}"
  chart-series-3:
    backgroundColor: "{colors.viz-3}"
  chart-series-4:
    backgroundColor: "{colors.viz-4}"
  chart-series-5:
    backgroundColor: "{colors.viz-5}"
  chart-series-6:
    backgroundColor: "{colors.viz-6}"
  chart-up:
    backgroundColor: "{colors.viz-up}"
  chart-down:
    backgroundColor: "{colors.viz-down}"
  secondary-text:
    textColor: "{colors.secondary}"
  tertiary-mark:
    backgroundColor: "{colors.tertiary}"
  neutral-surface:
    backgroundColor: "{colors.neutral}"
---`;
  return `${fm}

<!-- Generated by bausk-style ${meta.version} from tokens/looks/${look.id}/. Light-scheme values are listed;
     the dark scheme and all CSS variables are in the package (css/${look.id}.css, json/${look.id}.json).
     Agents: run \`npx bausk-style brief\` in the project for the full rules. -->

# ${brand.name.en} · ${look.name.en} (${look.name.uk})

${look.prose.trim()}
${projectRules ? `\n${projectRules.trim()}\n` : ''}`;
}
